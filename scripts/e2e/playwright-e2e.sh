#!/usr/bin/env bash
# Full admin Playwright E2E runner.
#
# Builds matched Leptos SSR/WASM assets, boots ersatzrs-web on an isolated
# SQLite database, runs the configured Playwright suite, and writes diagnostics
# under test-results/.

set -euo pipefail

REPO_ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
cd "$REPO_ROOT"

PORT="${ERSATZRS_E2E_PORT:-8409}"
BASE_URL="http://127.0.0.1:${PORT}"
WEB_CRATE="crates/ersatzrs-web"
RESULT_DIR="${ERSATZRS_E2E_RESULT_DIR:-test-results}"
RESULT_JSON="$RESULT_DIR/playwright-results.json"
SERVER_LOG="$RESULT_DIR/ersatzrs-web.log"

log() { printf '\033[1;34m[playwright-e2e]\033[0m %s\n' "$*"; }
err() { printf '\033[1;31m[playwright-e2e]\033[0m %s\n' "$*" >&2; }

WINDOWS_POSIX=0
case "$(uname -s)" in
  MINGW*|MSYS*|CYGWIN*) WINDOWS_POSIX=1 ;;
esac

native_env_path() {
  if [[ "$WINDOWS_POSIX" -eq 1 ]]; then
    cygpath -m "$1"
  else
    printf '%s\n' "$1"
  fi
}

LOCAL_FFMPEG_DIR="${ERSATZRS_FFMPEG_DIR:-$HOME/.local/ffmpeg-9.0}"
if [[ -x "$LOCAL_FFMPEG_DIR/bin/ffmpeg" ]]; then
  export LD_LIBRARY_PATH="$LOCAL_FFMPEG_DIR/lib${LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}"
  export ErsatzRS_FFMPEG__PATH="$LOCAL_FFMPEG_DIR/bin/ffmpeg"
  export ErsatzRS_FFPROBE__PATH="$LOCAL_FFMPEG_DIR/bin/ffprobe"
  log "using FFmpeg override at $LOCAL_FFMPEG_DIR"
else
  log "no FFmpeg override at $LOCAL_FFMPEG_DIR; startup may acquire the managed runtime"
fi

resolve_target_dir() {
  if [[ -n "${CARGO_TARGET_DIR:-}" ]]; then
    printf '%s\n' "$CARGO_TARGET_DIR"
    return
  fi

  local config_target=""
  if [[ -f .cargo/config.toml ]]; then
    config_target="$(awk '
      /^[[:space:]]*\[/ { section=$0; gsub(/[[:space:]]/,"",section); next }
      section=="[build]" && /^[[:space:]]*target-dir[[:space:]]*=/ {
        sub(/^[^=]*=[[:space:]]*/,"",$0); gsub(/^["'"'"']|["'"'"'][[:space:]]*$/,"",$0); print; exit
      }' .cargo/config.toml)"
  fi

  printf '%s\n' "${config_target:-target}"
}

TARGET_DIR="$(resolve_target_dir)"
case "$TARGET_DIR" in
  /*) TARGET_DIR_ABS="$TARGET_DIR" ;;
  *) TARGET_DIR_ABS="$REPO_ROOT/$TARGET_DIR" ;;
esac

command -v npx >/dev/null 2>&1 || { err "npx not found"; exit 1; }
command -v sqlite3 >/dev/null 2>&1 || { err "sqlite3 not found"; exit 1; }
command -v curl >/dev/null 2>&1 || { err "curl not found"; exit 1; }

if curl -fsS -m 2 "$BASE_URL/healthz" >/dev/null 2>&1; then
  err "$BASE_URL already serves an ErsatzRS health endpoint; stop it or set ERSATZRS_E2E_PORT"
  exit 1
fi
mkdir -p "$RESULT_DIR"

if [[ -n "${ERSATZRS_E2E_PREBUILT_DIR:-}" ]]; then
  log "verifying the shared CI build; rebuilding is disabled"
  python3 scripts/ci-build-artifacts.py verify --kind web \
    --directory "$ERSATZRS_E2E_PREBUILT_DIR" --sha "$(git rev-parse HEAD)"
  SERVER_BIN="$ERSATZRS_E2E_PREBUILT_DIR/bin/ersatzrs-web"
  SITE_ROOT="$ERSATZRS_E2E_PREBUILT_DIR/site"
else
command -v cargo >/dev/null 2>&1 || { err "cargo not found"; exit 1; }
command -v cargo-leptos >/dev/null 2>&1 || { err "cargo-leptos not found"; exit 1; }
command -v stylance >/dev/null 2>&1 || { err "stylance not found"; exit 1; }

# `bundle.css` is generated by the web crate's build script and is therefore
# removed by actions/checkout. A persistent Cargo target can reuse the prior
# build-script result without recreating that file in the fresh checkout, so
# generate it explicitly before cargo-leptos stages the public asset tree.
log "generating web CSS bundle with Stylance"
(cd "$WEB_CRATE" && stylance . --output-file public/bundle.css)
if [[ ! -s "$WEB_CRATE/public/bundle.css" ]]; then
  err "Stylance did not generate a non-empty $WEB_CRATE/public/bundle.css"
  exit 1
fi

if [[ "${ERSATZRS_SKIP_LEPTOS_BUILD:-0}" != "1" ]]; then
  log "building Leptos hydration assets with cargo leptos build"
  (cd "$WEB_CRATE" && cargo leptos build)
else
  log "ERSATZRS_SKIP_LEPTOS_BUILD=1; reusing existing hydration assets"
fi

SERVER_BIN="$TARGET_DIR_ABS/debug/ersatzrs-web"
if [[ "$WINDOWS_POSIX" -eq 1 && -x "${SERVER_BIN}.exe" ]]; then
  SERVER_BIN="${SERVER_BIN}.exe"
fi
if [[ ! -x "$SERVER_BIN" ]]; then
  err "server binary not found at $SERVER_BIN"
  exit 1
fi

PKG_JS="$(find "$REPO_ROOT/target" "$TARGET_DIR_ABS" "$WEB_CRATE/target" \
  -type f -name 'ersatzrs-web.js' -path '*/site/pkg/*' -printf '%T@ %p\n' 2>/dev/null \
  | sort -rn | head -1 | cut -d' ' -f2- || true)"
if [[ -z "$PKG_JS" ]]; then
  err "could not find built hydration bundle (pkg/ersatzrs-web.js)"
  exit 1
fi
SITE_ROOT="$(cd "$(dirname "$(dirname "$PKG_JS")")" && pwd)"

# cargo-leptos can preserve a warm site/pkg output while omitting the configured
# assets-dir from the site root. Copy the authoritative public assets after
# every build so a persistent target directory cannot produce a styled/hydrated
# bundle whose /public routes all return 404.
PUBLIC_SOURCE="$REPO_ROOT/$WEB_CRATE/public"
if [[ ! -d "$PUBLIC_SOURCE" ]]; then
  err "web public asset source not found at $PUBLIC_SOURCE"
  exit 1
fi
log "synchronizing web public assets into $SITE_ROOT"
cp -R "$PUBLIC_SOURCE/." "$SITE_ROOT/"

fi

for required_asset in \
  "bundle.css" \
  "channel-preview.js" \
  "vendor/hls/hls.mjs" \
  "vendor/hls/LICENSE"; do
  if [[ ! -f "$SITE_ROOT/$required_asset" ]]; then
    err "required web public asset missing after synchronization: $required_asset"
    exit 1
  fi
done

# SQL fixtures require repo-owned throwaway data. Leave TMPDIR unchanged so
# browser profile sockets keep their ordinary short system paths.
mkdir -p "$REPO_ROOT/tmp"
TMP_ROOT="$(mktemp -d "$REPO_ROOT/tmp/ersatzrs-playwright-e2e.XXXXXX")"
mkdir -p "$TMP_ROOT/home"
DB_PATH="$TMP_ROOT/ErsatzRS.db"
TMP_HOME_ENV="$(native_env_path "$TMP_ROOT/home")"
DB_PATH_ENV="$(native_env_path "$DB_PATH")"
SITE_ROOT_ENV="$(native_env_path "$SITE_ROOT")"
APP_STATE_DIR_ENV="$(native_env_path "$TMP_ROOT/home/.ersatzrs")"
APP_DATA_DIR_ENV="$(native_env_path "$TMP_ROOT/app-data/ErsatzRS")"
TMP_LOG="$TMP_ROOT/ersatzrs-web.log"
SERVER_PID=""

cleanup() {
  if [[ -n "$SERVER_PID" ]] && kill -0 "$SERVER_PID" 2>/dev/null; then
    kill "$SERVER_PID" 2>/dev/null || true
    wait "$SERVER_PID" 2>/dev/null || true
  fi
  if [[ -f "$TMP_LOG" ]]; then
    cp "$TMP_LOG" "$SERVER_LOG" 2>/dev/null || true
  fi
  if [[ "${ERSATZRS_E2E_KEEP_TEMP:-0}" == "1" ]]; then
    log "kept temp dir $TMP_ROOT"
  else
    rm -rf "$TMP_ROOT"
  fi
}
trap cleanup EXIT INT TERM

# Own the candidate for the entire suite. A concurrent local Leptos build can
# otherwise replace/remove pkg files while this host is serving its pages.
log "snapshotting the matched server and site into the isolated test runtime"
cp "$SERVER_BIN" "$TMP_ROOT/$(basename "$SERVER_BIN")"
mkdir -p "$TMP_ROOT/site"
cp -R "$SITE_ROOT/." "$TMP_ROOT/site/"
SERVER_BIN="$TMP_ROOT/$(basename "$SERVER_BIN")"
SITE_ROOT="$TMP_ROOT/site"
SITE_ROOT_ENV="$(native_env_path "$SITE_ROOT")"

log "starting ersatzrs-web on $BASE_URL"
log "database: $DB_PATH"
log "site root: $SITE_ROOT"
HOME="$TMP_HOME_ENV" \
ERSATZRS_APP_STATE_DIR="$APP_STATE_DIR_ENV" \
ERSATZRS_APP_DATA_DIR="$APP_DATA_DIR_ENV" \
DATABASE_URL="sqlite:$DB_PATH_ENV" \
LEPTOS_SITE_ROOT="$SITE_ROOT_ENV" \
LEPTOS_OUTPUT_NAME="ersatzrs-web" \
CARGO_MANIFEST_DIR="$REPO_ROOT/$WEB_CRATE" \
LEPTOS_SITE_ADDR="127.0.0.1:$PORT" \
RUST_LOG="${RUST_LOG:-warn,ersatzrs_web=info}" \
  "$SERVER_BIN" >"$TMP_LOG" 2>&1 &
SERVER_PID=$!

log "waiting for $BASE_URL/healthz"
HEALTHY=0
for _ in $(seq 1 180); do
  if ! kill -0 "$SERVER_PID" 2>/dev/null; then
    err "server exited during startup; last log lines:"
    tail -n 80 "$TMP_LOG" >&2 || true
    exit 1
  fi
  if curl -fsS -m 2 "$BASE_URL/healthz" >/dev/null 2>&1; then
    HEALTHY=1
    break
  fi
  sleep 1
done
if [[ "$HEALTHY" != "1" ]]; then
  err "/healthz never became reachable; last log lines:"
  tail -n 80 "$TMP_LOG" >&2 || true
  exit 1
fi

# Startup may acquire the managed FFmpeg runtime after this wrapper has already
# resolved its environment. Reuse that exact binary for browser fixtures when
# the caller did not provide an override and the runner has no FFmpeg on PATH.
MANAGED_FFMPEG="$TMP_ROOT/home/.ersatzrs/ffmpeg/current/bin/ffmpeg"
if [[ -z "${ErsatzRS_FFMPEG__PATH:-}" && \
      -z "${ERSATZRS_FFMPEG__PATH:-}" && \
      -z "${FFMPEG_PATH:-}" && \
      -x "$MANAGED_FFMPEG" ]]; then
  export FFMPEG_PATH="$(native_env_path "$MANAGED_FFMPEG")"
  log "using acquired managed FFmpeg for browser fixtures"
fi

if [[ "${ERSATZRS_SKIP_PW_INSTALL:-0}" != "1" ]]; then
  npx --yes playwright install chromium firefox >/dev/null 2>&1 || \
    log "playwright browser install skipped or failed; assuming browsers are present"
fi

log "running Playwright suite"
PLAYWRIGHT_ARGS=("$@")
HAS_WORKERS_ARG=0
for arg in "${PLAYWRIGHT_ARGS[@]}"; do
  case "$arg" in
    --workers|--workers=*)
      HAS_WORKERS_ARG=1
      ;;
  esac
done
if [[ "$HAS_WORKERS_ARG" != "1" ]]; then
  PLAYWRIGHT_ARGS+=(--workers="${ERSATZRS_E2E_WORKERS:-1}")
fi

set +e
ERSATZRS_BASE_URL="$BASE_URL" \
E2E_BASE_URL="$BASE_URL" \
E2E_DB_PATH="$DB_PATH_ENV" \
ERSATZRS_DB_PATH="$DB_PATH_ENV" \
E2E_APP_STATE_DIR="$APP_STATE_DIR_ENV" \
E2E_SERVER_BIN="$(native_env_path "$SERVER_BIN")" \
E2E_SITE_ROOT="$SITE_ROOT_ENV" \
E2E_SPONSORBLOCK_HOST_LOG="$(native_env_path "$TMP_LOG")" \
PLAYWRIGHT_JSON_OUTPUT_NAME="$RESULT_JSON" \
  npx --yes playwright test "${PLAYWRIGHT_ARGS[@]}" --reporter=line,json
STATUS=$?
set -e

if [[ "$STATUS" -eq 0 ]]; then
  log "PASS - Playwright suite completed"
else
  err "FAIL - Playwright suite failed"
fi
log "result json: $RESULT_JSON"
log "server log: $SERVER_LOG"
exit "$STATUS"
