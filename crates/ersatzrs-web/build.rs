#[allow(clippy::disallowed_methods)]
fn main() {
    println!("cargo:rerun-if-changed=src/admin");
    write_language_registry();

    if std::env::var("ERSATZRS_SKIP_STYLANCE").as_deref() == Ok("1") {
        return;
    }

    // Cross-compile and minimal-tooling builds (e.g. `cross build`) ship the
    // CSS bundle from the leptos host build instead of regenerating it here.
    // Warn and continue when stylance-cli is missing so those builds succeed.
    // Read at run time, like OUT_DIR below: see write_language_registry.
    let status = match std::process::Command::new("stylance")
        .arg(std::env::var_os("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"))
        .args(["--output-file", "public/bundle.css"])
        .status()
    {
        Ok(status) => status,
        Err(e) => {
            println!(
                "cargo:warning=stylance-cli not found ({e}); \
                 skipping CSS bundle regeneration. \
                 Install with `cargo install stylance-cli` for host builds."
            );
            return;
        }
    };

    assert!(status.success(), "stylance bundle failed");
}

#[allow(clippy::disallowed_methods)]
fn write_language_registry() {
    use std::fmt::Write as _;

    // Read CARGO_MANIFEST_DIR when the build script runs, not with env!. env!
    // bakes the checkout path into the compiled build script, and Cargo reuses
    // that binary when a target dir is moved to another checkout path, so the
    // script would then read the old, missing checkout.
    let manifest_dir = std::path::PathBuf::from(
        std::env::var_os("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"),
    );
    let languages_dir = manifest_dir.join("src/admin/languages");
    println!("cargo:rerun-if-changed={}", languages_dir.to_string_lossy());

    let mut entries = std::fs::read_dir(&languages_dir)
        .expect("read admin language directory")
        .filter_map(Result::ok)
        .map(|entry| entry.path())
        .filter(|path| {
            path.extension().is_some_and(|extension| extension == "rs")
                && path.file_stem().is_some_and(|stem| stem != "mod")
        })
        .filter_map(|path| {
            let source = std::fs::read_to_string(&path).expect("read admin language file");
            if source
                .lines()
                .any(|line| line.trim() == "pub const TRANSLATION_COMPLETE: bool = false;")
            {
                return None;
            }
            let order = language_sort_order(&source, &path);
            let module = path
                .file_stem()
                .expect("language module file stem")
                .to_string_lossy()
                .into_owned();
            Some((order, module, path))
        })
        .collect::<Vec<_>>();
    entries.sort_by(|left, right| left.0.cmp(&right.0).then_with(|| left.1.cmp(&right.1)));
    for pair in entries.windows(2) {
        assert_ne!(
            pair[0].0,
            pair[1].0,
            "duplicate admin language SORT_ORDER {} in {} and {}",
            pair[0].0,
            pair[0].2.display(),
            pair[1].2.display()
        );
    }

    let mut generated = String::new();
    generated.push_str("// @generated by crates/ersatzrs-web/build.rs\n");
    for (_, module, path) in &entries {
        let path = path.to_string_lossy();
        writeln!(
            generated,
            "#[allow(clippy::match_same_arms, clippy::too_many_lines)]\npub mod {module} {{ include!({path:?}); }}"
        )
        .expect("write generated language module");
    }
    generated.push('\n');
    generated.push_str("pub static LANGUAGES: &[crate::admin::i18n::LanguageDefinition] = &[\n");
    for (_, module, _) in &entries {
        writeln!(
            generated,
            "    crate::admin::i18n::LanguageDefinition {{ code: {module}::CODE, label: {module}::LABEL, aliases: {module}::ALIASES, strings: &{module}::STRINGS }},"
        )
        .expect("write generated language definition");
    }
    generated.push_str("];\n");

    let out_dir = std::path::PathBuf::from(std::env::var_os("OUT_DIR").expect("OUT_DIR"));
    std::fs::write(out_dir.join("admin_languages.rs"), generated)
        .expect("write generated admin language registry");
}

fn language_sort_order(source: &str, path: &std::path::Path) -> u16 {
    let line = source
        .lines()
        .find(|line| line.trim_start().starts_with("pub const SORT_ORDER: u16 ="))
        .unwrap_or_else(|| panic!("{} missing SORT_ORDER", path.display()));
    line.split('=')
        .nth(1)
        .and_then(|value| value.trim().trim_end_matches(';').parse().ok())
        .unwrap_or_else(|| panic!("{} has invalid SORT_ORDER", path.display()))
}
